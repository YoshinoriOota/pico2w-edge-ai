/**
 * @brief Affine関数の実行コールバック(ダミー実装)
 * @param f 対象関数のコンテキスト(未使用)
 * @return 常にRT_FUNCTION_ERROR_NOERROR
 */
static rt_function_error_t cb_exec(rt_function_t *f) {
  (void)f;
  printf("  [callback] cb_exec called\n");
  return RT_FUNCTION_ERROR_NOERROR;
}

/**
 * @brief Affine関数のローカルコンテキスト解放コールバック(ダミー実装)
 * @param f 対象関数のコンテキスト(未使用)
 * @return 常にRT_FUNCTION_ERROR_NOERROR
 */
static rt_function_error_t cb_free(rt_function_t *f) {
  (void)f;
  return RT_FUNCTION_ERROR_NOERROR;
}

/**
 * @brief Affine関数(impl==1)用のコールバック登録関数
 *
 * affine_nnb 内のAffine関数はimplフラグが1に設定されているため、
 * rt_initialize_context() からこの関数が呼び出される。
 * cb_exec/cb_free を実行関数として登録する。
 *
 * @param net             NNBネットワーク全体(未使用)
 * @param function_context 対象関数のコンテキスト(rt_function_context_t*)
 * @return implが1ならRT_RET_FUNCTION_MATCH、それ以外はRT_RET_FUNCTION_DONT_MATCH
 */
static rt_return_value_t cb_alloc(nn_network_t *net, void *function_context) {
  (void)net;
  rt_function_context_t *func = (rt_function_context_t *)function_context;
  if ((int)func->info->impl != 1) {
    return RT_RET_FUNCTION_DONT_MATCH;
  }

  func->func.exec_func = cb_exec;
  func->func.free_local_context_func = cb_free;
  return RT_RET_FUNCTION_MATCH;
}

/**
 * @brief エントリポイント
 *
 * DNNRTの一連のAPI (rt_allocate_context -> rt_initialize_context ->
 * rt_forward -> rt_free_context) をRP2350上で実行し、結果をUSBシリアルへ
 * 出力する。
 *
 * @return 使用しない (組み込みのため戻らない)
 */
int main(void) {
  stdio_init_all();

  /* USBシリアル接続待ち */
  sleep_ms(3000);

  printf("=== DNNRT RP2350 inference smoke test ===\n");
  printf("NNabla version    : %s\n", rt_nnabla_version());
  printf("C-Runtime version : %s\n", rt_c_runtime_version());
  printf("NNB format version: %d\n", rt_nnb_version());

  rt_context_pointer context = 0;
  rt_return_value_t ret = rt_allocate_context(&context);

  if (ret == RT_RET_NOERROR) {
    ret = rt_add_callback(context, NN_FUNCTION_AFFINE, cb_alloc);
  }

  if (ret == RT_RET_NOERROR) {
    nn_network_t *net = (nn_network_t *)affine_nnb;
    ret = rt_initialize_context(context, net);
  }

  if (ret == RT_RET_NOERROR) {
    printf("inputs : %d\n", rt_num_of_input(context));
    printf("outputs: %d\n", rt_num_of_output(context));

    int in_size = rt_input_size(context, 0);
    printf("input[0] size: %d (dummy data: %u bytes)\n", in_size,
           (unsigned)sizeof(input_data));

    if (in_size == (int)sizeof(input_data)) {
      memcpy(rt_input_buffer(context, 0), input_data, sizeof(input_data));

      ret = rt_forward(context);
      printf("rt_forward: %s\n", (ret == RT_RET_NOERROR) ? "OK" : "NG");

      int out_size = rt_output_size(context, 0);
      printf("output[0] size: %d\n", out_size);
    } else {
      printf("input size mismatch, skip rt_forward\n");
    }

    ret = rt_free_context(&context);
    printf("rt_free_context: %s\n", (ret == RT_RET_NOERROR) ? "OK" : "NG");
  } else {
    printf("DNNRT initialization failed (ret=%d)\n", ret);
  }

  printf("=== done ===\n");

  while (1) {
    tight_loop_contents();
  }
}
